-- Class survey schema for class_dataset.csv (PostgreSQL)

DROP TABLE IF EXISTS student_availability CASCADE;
DROP TABLE IF EXISTS student_tools CASCADE;
DROP TABLE IF EXISTS availability_slots CASCADE;
DROP TABLE IF EXISTS tools CASCADE;
DROP TABLE IF EXISTS students CASCADE;
DROP TYPE IF EXISTS school_year CASCADE;
DROP TYPE IF EXISTS intro_programming CASCADE;

CREATE TYPE school_year AS ENUM ('Freshman', 'Sophomore', 'Junior', 'Senior');
CREATE TYPE intro_programming AS ENUM ('took_it', 'equivalent', 'neither');

CREATE TABLE students (
    netid                   VARCHAR(16) PRIMARY KEY,
    name                    VARCHAR(64) NOT NULL,
    school_year             school_year NOT NULL,
    intro_programming       intro_programming NOT NULL,
    skill_programming       SMALLINT NOT NULL CHECK (skill_programming BETWEEN 1 AND 5),
    skill_data_stats        SMALLINT NOT NULL CHECK (skill_data_stats BETWEEN 1 AND 5),
    skill_frontend_design   SMALLINT NOT NULL CHECK (skill_frontend_design BETWEEN 1 AND 5),
    skill_business_pitch    SMALLINT NOT NULL CHECK (skill_business_pitch BETWEEN 1 AND 5),
    working_style           TEXT,
    interests               TEXT,
    semester_goal           TEXT,
    submitted_at            TIMESTAMPTZ NOT NULL
);

CREATE TABLE tools (
    tool_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(32) NOT NULL UNIQUE
);

CREATE TABLE student_tools (
    netid       VARCHAR(16) NOT NULL REFERENCES students(netid) ON DELETE CASCADE,
    tool_id     INTEGER NOT NULL REFERENCES tools(tool_id) ON DELETE CASCADE,
    PRIMARY KEY (netid, tool_id)
);

CREATE TABLE availability_slots (
    slot_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(32) NOT NULL UNIQUE
);

CREATE TABLE student_availability (
    netid       VARCHAR(16) NOT NULL REFERENCES students(netid) ON DELETE CASCADE,
    slot_id     INTEGER NOT NULL REFERENCES availability_slots(slot_id) ON DELETE CASCADE,
    PRIMARY KEY (netid, slot_id)
);

CREATE INDEX idx_student_tools_tool ON student_tools(tool_id);
CREATE INDEX idx_student_availability_slot ON student_availability(slot_id);
CREATE INDEX idx_students_year ON students(school_year);
CREATE INDEX idx_students_intro ON students(intro_programming);
